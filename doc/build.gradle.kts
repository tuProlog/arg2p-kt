val baseUrl: String? = findProperty("baseUrl")?.toString()

plugins {
    id("io.github.fstaudt.hugo") version "0.13.0"
}

hugo {
    version = "0.166.0"
}

// The latest released version, as advertised by the dependency snippets in the site.
// The project version is not usable here: the documentation is deployed from master, where
// git-sem-ver yields a development version (e.g. 0.16.3-dev02-fc204a3) rather than a released one.
val latestReleasedVersion =
    providers.exec {
        commandLine("git", "describe", "--tags", "--abbrev=0")
    }.standardOutput.asText.map { it.trim() }

val generateVersionData =
    tasks.register("generateVersionData") {
        val version = latestReleasedVersion
        val destination = layout.projectDirectory.file("site/data/arg2p.json")
        inputs.property("version", version)
        outputs.file(destination)
        doLast {
            destination.asFile.apply {
                parentFile.mkdirs()
                writeText("{ \"version\": \"${version.get()}\" }\n")
            }
        }
    }

// The reference of the Prolog modules, generated from their sources (see :core:prologDocs)
val prologModulePages =
    tasks.register<Sync>("prologModulePages") {
        group = "documentation"
        description = "Copies the pages of the Prolog modules into the site (site/content/docs/api/prolog)"
        dependsOn(":core:prologDocs")
        from(project(":core").layout.buildDirectory.dir("docs/prolog-modules"))
        into(layout.projectDirectory.dir("site/content/docs/api/prolog"))
    }

// The Kotlin & JS reference, generated by Dokka, published as it is under api/reference
val kotlinReference =
    tasks.register<Sync>("kotlinReference") {
        group = "documentation"
        description = "Copies the Kotlin & JS reference made by Dokka into the site (site/static/api/reference)"
        dependsOn(":dokkaGeneratePublicationHtml")
        from(rootProject.layout.buildDirectory.dir("dokka/html"))
        into(layout.projectDirectory.dir("site/static/api/reference"))
    }

tasks.hugoServer {
    dependsOn(generateVersionData, prologModulePages, kotlinReference)
}

tasks.hugoBuild {
    dependsOn(generateVersionData, prologModulePages, kotlinReference)
    args = "--gc --minify --baseURL $baseUrl"
}
