import org.jetbrains.kotlin.gradle.plugin.KotlinPlatformType

plugins {
    // the JDKs of the toolchains, for the Java runtime of the package
    `jvm-toolchains`
}

// The Python package (see README.md): the library of the JVM, the umbrella project with every module of arg2p, run
// through JPype. The package carries its jars and its version, and a wheel for a platform a Java runtime of its own.

val jvmVersion: String = libs.versions.jvm.get()

// The interpreter running the tests (-Ppython=.venv/bin/python, say): python on the path otherwise
val python: String = findProperty("python")?.toString() ?: "python"

// The jars of the umbrella project on the JVM, those of its MCP server (arg2p mcp), and those they depend on
val jars by configurations.creating {
    isCanBeConsumed = false
    attributes {
        attribute(Usage.USAGE_ATTRIBUTE, objects.named(Usage.JAVA_RUNTIME))
        attribute(KotlinPlatformType.attribute, KotlinPlatformType.jvm)
    }
}

dependencies {
    jars(project(":"))
    jars(project(":lsp"))
}

val pythonJars by tasks.registering(Sync::class) {
    group = "python"
    description = "Copies the jars of arg2p on the JVM into the package (src/arg2p/jars)"
    from(jars)
    into(layout.projectDirectory.dir("src/arg2p/jars"))
}

// The version of arg2p as Python writes it (PEP 440): a release as it is, a development version (0.18.2-dev0l-3dbbda1)
// as a development release of the next one (0.18.2.dev21+3dbbda1)
val pythonVersion by tasks.registering {
    group = "python"
    description = "Writes the version of arg2p into the package (src/arg2p/_version.py)"
    val version = provider { rootProject.version.toString() }
    val output = layout.projectDirectory.file("src/arg2p/_version.py")
    inputs.property("version", version)
    outputs.file(output)
    doLast {
        val development = Regex("""^(\d+\.\d+\.\d+)-dev([0-9a-z]+)-([0-9a-f]+)$""").matchEntire(version.get())
        val pep440 =
            development?.destructured?.let { (release, distance, commit) -> "$release.dev${distance.toInt(36)}+$commit" }
                ?: version.get().replace('-', '+')
        output.asFile.writeText(
            "# Generated by the build (./gradlew :python:pythonVersion): the version of arg2p\n__version__ = \"$pep440\"\n",
        )
    }
}

// The modules of the Java runtime arg2p needs (jdeps on its jars and those of its MCP server, with those the WebSockets
// and their TLS need)
val runtimeModules =
    listOf(
        "java.base",
        "java.logging",
        "java.management",
        "java.naming",
        "java.net.http",
        "java.sql",
        "java.xml",
        "jdk.crypto.ec",
        "jdk.unsupported",
    )

val pythonRuntime by tasks.registering(Exec::class) {
    group = "python"
    description = "Makes the Java runtime the package bundles, for this platform (src/arg2p/jre)"
    val jdk = javaToolchains.compilerFor { languageVersion.set(JavaLanguageVersion.of(jvmVersion)) }
    val output = layout.projectDirectory.dir("src/arg2p/jre")
    outputs.dir(output)
    doFirst { delete(output) }
    executable(jdk.map { it.metadata.installationPath.file("bin/jlink").asFile.absolutePath }.get())
    args(
        "--add-modules",
        runtimeModules.joinToString(","),
        "--strip-debug",
        "--no-header-files",
        "--no-man-pages",
        "--compress",
        "zip-6",
        "--output",
        output.asFile.absolutePath,
    )
}

tasks.register<Exec>("pythonTest") {
    group = "python"
    description = "Runs the tests of the package (with the interpreter of -Ppython, the package installed in it)"
    dependsOn(pythonJars, pythonVersion)
    workingDir = projectDir
    commandLine(python, "-m", "pytest")
}
